import re
import uuid

from app.coding.schemas import (
    CodeChangeProposal,
    CodePublishResult,
)

from app.connectors.github import (
    GITHUB_BRANCH,
    create_branch,
    create_pull_request,
    get_branch_sha,
    get_file_sha,
    update_file,
)


def _build_branch_name(
    proposal: CodeChangeProposal,
) -> str:

    filename = (
        proposal.file_path
        .rsplit("/", 1)[-1]
        .rsplit(".", 1)[0]
    )

    safe_name = re.sub(
        r"[^a-zA-Z0-9-]+",
        "-",
        filename,
    ).strip("-").lower()

    suffix = uuid.uuid4().hex[:8]

    return (
        f"atlasops/"
        f"ai-{safe_name}-{suffix}"
    )


def publish_code_change(
    proposal: CodeChangeProposal,
) -> CodePublishResult:

    # ==========================================
    # 1. SNAPSHOT CURRENT BASE BRANCH
    # ==========================================

    base_commit_sha = get_branch_sha(
        GITHUB_BRANCH
    )

    # ==========================================
    # 2. REVALIDATE FILE VERSION
    # ==========================================

    current_file_sha = get_file_sha(
        path=proposal.file_path,
        ref=base_commit_sha,
    )

    if (
        current_file_sha
        != proposal.original_sha
    ):
        raise RuntimeError(
            "The source file changed in GitHub "
            "after the proposal was generated. "
            "Publication was aborted to avoid "
            "overwriting newer code."
        )

    # ==========================================
    # 3. CREATE ISOLATED BRANCH
    # ==========================================

    branch_name = _build_branch_name(
        proposal
    )

    create_branch(
        branch_name=branch_name,
        from_sha=base_commit_sha,
    )

    # ==========================================
    # 4. UPDATE FILE + COMMIT
    # ==========================================

    commit_sha = update_file(
        path=proposal.file_path,
        content=proposal.proposed_content,
        original_sha=proposal.original_sha,
        branch=branch_name,
        commit_message=(
            f"AtlasOps: {proposal.summary}"
        ),
    )

    # ==========================================
    # 5. CREATE PULL REQUEST
    # ==========================================

    pull_request = create_pull_request(
        branch=branch_name,
        title=(
            f"AtlasOps: "
            f"{proposal.summary}"
        ),
        body=(
            "This Pull Request was generated by AtlasOps.\n\n"
            "Safety pipeline:\n"
            "- Code RAG\n"
            "- deterministic validation\n"
            "- authorization\n"
            "- policy evaluation\n"
            "- human approval\n"
            "- SHA revalidation before publication\n\n"
            f"Changed file: `{proposal.file_path}`\n\n"
            f"Reason: {proposal.reason}\n\n"
            "AtlasOps does not write directly to the "
            "base branch."
        ),
        base_branch=GITHUB_BRANCH,
    )

    return CodePublishResult(
        branch=branch_name,
        commit_sha=commit_sha,
        pull_request_number=(
            pull_request["number"]
        ),
        pull_request_url=(
            pull_request["url"]
        ),
    )